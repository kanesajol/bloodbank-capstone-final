    public function run(): void
    {
        $createdDonors = 0;
        $createdDonations = 0;
        $skippedRecords = 0;

        DB::transaction(function () use (&$createdDonors, &$createdDonations, &$skippedRecords): void {
            foreach ($this->records() as $record) {
                if ($this->alreadyImported($record)) {
                    $skippedRecords++;

                    continue;
                }

                $donor = Donor::query()
                    ->whereRaw('LOWER(full_name) = ?', [mb_strtolower($record['full_name'])])
                    ->first();

                if ($donor === null) {
                    $donor = Donor::query()->create([
                        'full_name' => $record['full_name'],
                        'first_name' => $record['first_name'],
                        'middle_name' => $record['middle_name'],
                        'last_name' => $record['last_name'],
                        'blood_type' => $record['blood_type'],
                        'age' => $record['age'],
                        'gender' => $record['gender'],
                        'barangay' => '',
                        'municipality' => '',
                        'province' => null,
                        'contact' => $record['contact'],
                        'birthdate' => $record['birthdate'],
                        'registered_date' => $record['donated_on'],
                    ]);

                    $createdDonors++;
                }

                $donor->donations()->create([
                    'donated_on' => $record['donated_on'],
                    'blood_type' => $record['blood_type'],
                    'location' => $record['location'],
                    'bags' => $record['bags'],
                    'mbd_date' => $record['mbd_date'],
                    'serial_number' => $record['serial_number'],
                    'status' => $record['status'],
                    'reason_for_deferral' => $record['reason_for_deferral'],
                    'reserved_for_px' => $record['reserved_for_px'],
                    'remarks' => $record['remarks'],
                ]);

                $createdDonations++;
            }
        });

        if ($this->command !== null) {
            $this->command->table(
                ['New donor profiles', 'New donation records', 'Existing records skipped'],
                [[$createdDonors, $createdDonations, $skippedRecords]],
            );
        }
    }

    /**
     * @param  array<string, mixed>  $record
     */
    private function alreadyImported(array $record): bool
    {
        $serialNumbers = array_filter([
            $record['serial_number'],
            $record['existing_serial_number'] ?? null,
        ]);

        if ($serialNumbers !== [] && Donation::query()->whereIn('serial_number', $serialNumbers)->exists()) {
            return true;
        }

        $names = array_map(
            fn (string $name): string => mb_strtolower($name),
            array_merge([$record['full_name']], $record['existing_name_aliases'] ?? []),
        );

        return Donation::query()
            ->whereDate('donated_on', $record['donated_on'])
            ->whereHas('donor', function (Builder $query) use ($names): void {
                $query->whereIn(DB::raw('LOWER(full_name)'), $names);
            })
            ->exists();
    }

